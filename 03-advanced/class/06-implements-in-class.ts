/**
 * Базовый тип (контракт). 
 * Любой класс, который его "имплементирует", обязан реализовать метод blockUser.
 */
type BaseUser = {
  blockUser: (id: number) => void;
}

/**
 * Ключевое слово `implements` говорит TypeScript, что класс должен 
 * строго соответствовать структуре типа `BaseUser`.
 * 
 * Важно:
 * 1. Метод `blockUser` обязателен для реализации.
 * 2. Класс может содержать любые другие собственные свойства и методы.
 */

// Пример 1: Успешная реализация + собственное свойство `name`
class User implements BaseUser {
  name = 'Alex'; // Уникальное свойство класса User
  
  blockUser = (id: number) => {
    // Реализация метода по контракту
  };
}

// Пример 2: Успешная реализация + собственный метод `sayHello`
class Moder implements BaseUser {
  sayHello = () => {
    // Уникальный метод класса Moder
  }; 
  
  blockUser = (id: number) => {
    // Реализация метода по контракту
  };
}

// Пример 3: Демонстрация работы контракта
class Admin implements BaseUser {
  dsfgsfxzc = () => {}; // Какое-то кастомное свойство

  /**
   * ЕСЛИ УДАЛИТЬ ИЛИ ЗАКОММЕНТИРОВАТЬ ЭТУ СТРОКУ:
   * TypeScript выдаст ошибку уровня компиляции: 
   * "Class 'Admin' incorrectly implements type 'BaseUser'."
   * Это защищает от ошибок и гарантирует наличие метода.
   */
  blockUser = (id: number) => {
    // Метод успешно реализован, ошибка пропала
  };
}

// Создаем экземпляр класса Admin и вызываем метод
const admin = new Admin();
admin.blockUser(2342);