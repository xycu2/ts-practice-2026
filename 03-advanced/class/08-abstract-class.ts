/**
 * АБСТРАКТНЫЙ КЛАСС (Abstract Class)
 * Используем, когда у нас есть общая логика (шаблон, готовые методы или свойства),
 * которую мы хотим передать дочерним классам, но сам по себе этот класс 
 * не должен создаваться напрямую через `new`.
 */
abstract class AbstractUser {
  // Конструктор общий для всех наследников: избавляет от дублирования кода
  constructor(
    public name: string,
    public age: number,
  ) {}

  // Готовая общая логика (метод), которая сразу будет доступна в дочерних классах
  getInfo = () => {
    return `${this.name}, возраст: ${this.age}`;
  }

  /**
   * АБСТРАКТНЫЕ МЕТОДЫ И СВОЙСТВА
   * Ключевое слово `abstract` означает: 
   * "У меня нет здесь реализации, но каждый класс, который от меня унаследуется, 
   * ОБЯЗАН написать эти методы самостоятельно".
   */
  abstract render: (name: string, age: number) => void;
  abstract blockUser: (id: number) => void;
}

// ОШИБКА: new AbstractUser('ALex', 22) 
// С использованием ключевого слова abstract мы НЕ МОЖЕМ создавать этот класс через new напрямую.
// Он служит исключительно базой (шаблоном) для других классов.


/**
 * ДОЧЕРНИЙ КЛАСС (Наследник)
 * Ключевое слово `extends` связывает его с AbstractUser.
 */
class User extends AbstractUser  { 
  // Свойства name и age уже автоматически пришли из конструктора AbstractUser, 
  // поэтому их не нужно объявлять заново.
  
  test = ''; // Собственное уникальное свойство, характерное только для класса User
  
  // Обязательная реализация абстрактного метода из родительского класса
  blockUser = (id: number) => {
    // Здесь пишется конкретная логика блокировки пользователя
  };

  // Обязательная реализация второго абстрактного метода
  render = () => {
    // Здесь пишется конкретная логика отрисовки
  };
}

// Создаем экземпляр уже обычного (не абстрактного) класса User
const user = new User('Demid', 15); // Нам доступны все свойства и методы (и общие, и уникальные)


