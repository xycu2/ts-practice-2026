/**
 * Обобщенный класс (дженерик) MyStorage для хранения и управления массивом данных.
 * Ограничение `<T extends unknown[]>` указывает, что тип T обязатленнó должен быть массивом 
 * (любым массивом, состоящим из элементов типа unknown).
 */
class MyStorage<T extends unknown[]> {
  
  /**
     * Конструктор класса.
     * Принимает параметр `data`, который по умолчанию является пустым массивом (`[]`).
     * 
     * Конструкция `as unknown as T` (двойное приведение типов) необходима, потому что 
     * пустой массив `[]` TypeScript по умолчанию считает типом `never[]`. Без этого кастования 
     * компилятор выдаст ошибку попытки присвоить `never[]` в неизвестный заранее тип `T`.
     * Модификатор `private` автоматически создает и инициализирует приватное свойство `data`.
     */
  constructor(private data: T = [] as unknown as T) {}

  /**
     * Метод для добавления нового элемента в хранилище.
     * 
     * `T[number]` — это специальный синтаксис TypeScript (Indexed Access Types). 
     * Он берет тип массива `T` и извлекает из него тип одного элемента по его числовому индексу.
     * Например, если T — это `string[]`, то `T[number]` превратится в обычный `string`.
     */
  addData = (value: T[number]) => {
    this.data.push(value)
  }

  /**
     * Метод для получения элемента из хранилища по его индексу.
     * 
     * Принимает индекс (`index: number`) и возвращает элемент, тип которого 
     * точно так же определяется через `T[number]` (тип элемента внутри массива `T`).
     */
  getDataByIndex = (index: number): T[number] => {
    return this.data[index]
  }
}

// ==========================================
// Пример использования класса:
// ==========================================

// Создаем экземпляр класса MyStorage, явно передавая в качестве типа T массив строк (string[]).
// Теперь вместо буквы T компилятор подставит везде `string[]`.
const myStorage = new MyStorage<string[]>()

// Добавляем пустую строку в хранилище. 
// Так как T[number] для string[] эквивалентен `string`, метод принимает строки.
myStorage.addData('')

// Получаем элемент по индексу 0.
// TypeScript на основе сигнатуры метода автоматически выводит, что константа `data` будет иметь тип `string`.
const data = myStorage.getDataByIndex(0) // тип: string

export {}